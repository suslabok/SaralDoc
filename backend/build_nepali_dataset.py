def main():
    rows = []
    for label, texts in NEPALI_CLAUSES.items():
        for text in texts:
            rows.append((text, label, "nepali", "hand_authored"))
    for label, texts in NEPALI_CLAUSES_TRANSLATED.items():
        for text in texts:
            rows.append((text, label, "nepali", "translated_from_cuad_concept"))

    OUT_DIR.mkdir(exist_ok=True)
    out_path = OUT_DIR / "nepali_clause_dataset.csv"
    with open(out_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["text", "label", "language", "source"])
        writer.writerows(rows)

    print(f"Wrote {len(rows)} Nepali examples to {out_path}")
    from collections import Counter
    print("Label distribution:", dict(Counter(r[1] for r in rows)))
    print("Source distribution:", dict(Counter(r[3] for r in rows)))


if __name__ == "__main__":
    main()
